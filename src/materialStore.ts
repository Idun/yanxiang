export const materialStore = reactive({
  items: [] as MaterialItem[],
});

export function ensureDefaultMaterials(): void {
  for (const d of DEFAULT_MATERIALS) {
    if (!materialStore.items.some((m) => m.id === d.id)) {
      materialStore.items.push({ ...d });
    }
  }
}

/** 素材库顺序修正：把「倒推五线手法」固定放到「五线写作原则」正下方，
    其余素材相对顺序保持不变；已满足时直接幂等返回。用于修正旧版本
    persist 下来的既有顺序（只改默认顺序对已有数据不生效）。 */
export function normalizeMaterialOrder(): void {
  const arr = materialStore.items;
  const anchorId = "material_五线写作原则";
  const movedId = "material_倒推五线手法";
  let anchor = arr.findIndex((m) => m.id === anchorId);
  const moving = arr.findIndex((m) => m.id === movedId);
  if (anchor === -1 || moving === -1 || moving === anchor + 1) return;
  const [item] = arr.splice(moving, 1);
  anchor = arr.findIndex((m) => m.id === anchorId);
  arr.splice(anchor + 1, 0, item);
}

export function selectedMaterials(): MaterialItem[] {
  return materialStore.items.filter((m) => m.selected);
}

export function createMaterial(title: string, content: string): MaterialItem {
  const item: MaterialItem = {
    id: `material_${Date.now()}_${Math.random().toString(36).slice(2, 7)}`,
    title: title.trim() || "未命名素材",
    content: content.trim(),
    selected: false,
  };
  materialStore.items.push(item);
  return item;
}

export function updateMaterial(id: string, title: string, content: string): void {
  const item = materialStore.items.find((m) => m.id === id);
  if (!item) return;
  if (title.trim()) item.title = title.trim();
  item.content = content.trim();
}

export function toggleMaterial(id: string): void {
  const item = materialStore.items.find((m) => m.id === id);
  if (item) item.selected = !item.selected;
}

export function removeMaterial(id: string): void {
  materialStore.items = materialStore.items.filter((m) => m.id !== id);
}